import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { test } from 'node:test';
import ts from 'typescript';
const source = readFileSync(new URL('../src/services/api/circulosApi.ts', import.meta.url), 'utf8');
const js = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.ESNext } }).outputText.replace(/import \{ requisicaoApi \} from ".\/clienteApi";/, 'const requisicaoApi = (...args) => globalThis.chamadaCirculo(...args);');
const api = await import('data:text/javascript;base64,' + Buffer.from(js).toString('base64'));
test('contratos e permissões de transporte dos círculos', async () => {
  const chamadas = [];
  globalThis.chamadaCirculo = async (rota, opcoes) => { chamadas.push({ rota, ...opcoes }); };
  await api.criarCirculo(' Família ', 'jwt');
  await api.entrarNoCirculo(' ABC123 ', 'jwt');
  await api.alterarFuncao('123','456','ADMINISTRADOR','jwt');
  await api.sairCirculo('123','jwt');
  await api.removerMembro('123','456','jwt');
  await api.desbloquearMembro('123','456','jwt');
  await api.excluirCirculo('123','jwt');
  assert.deepEqual(JSON.parse(chamadas[0].body), { nome: 'Família' });
  assert.deepEqual(JSON.parse(chamadas[1].body), { codigoConvite: 'ABC123' });
  assert.deepEqual(JSON.parse(chamadas[2].body), { funcao: 'ADMINISTRADOR' });
  assert.equal(chamadas[3].rota, '/circulos/123/membros/eu');
  assert.equal(chamadas[4].rota, '/circulos/123/membros/456');
  assert.equal(chamadas[5].rota, '/circulos/123/bloqueios/456');
  assert.equal(chamadas[6].method, 'DELETE');
  assert.ok(chamadas.every(c => c.token === 'jwt'));
  assert.throws(() => api.listarCirculos(''), /Entre/);
  assert.throws(() => api.criarCirculo('ab','jwt'), /nome/);
  assert.throws(() => api.desbloquearMembro('123','abc','jwt'), /ID/);
  await api.buscarCirculo("123", "jwt");
  assert.equal(chamadas.at(-1).rota, "/circulos/123");
  await api.desbloquearMembroPorEmail('123', ' TESTE@EXEMPLO.COM ', 'jwt');
  assert.equal(chamadas.at(-1).rota, '/circulos/123/bloqueios/desbloquear-por-email');
  assert.equal(chamadas.at(-1).method, 'POST');
  assert.deepEqual(JSON.parse(chamadas.at(-1).body), { email: 'teste@exemplo.com' });
  assert.throws(() => api.desbloquearMembroPorEmail('123', 'invalido', 'jwt'), /e-mail/);
  assert.throws(() => api.desbloquearMembroPorEmail('123', 'teste@exemplo.com', ''), /Entre/);
  delete globalThis.chamadaCirculo;
});
